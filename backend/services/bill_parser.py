def _money_values(text):
    if not text:
        return []

    values = []

    # Comma-formatted MSEDCL amounts first.
    patterns = [
        r"₹?\s*(\d{1,3}(?:,\d{3})+(?:\.\d{1,2})?)",
        r"₹?\s*(\d{4,}(?:\.\d{1,2})?)",
    ]

    for pattern in patterns:
        for m in re.finditer(pattern, text):
            value = clean_number(m.group(1))

            if value is None:
                continue

            if 100 <= value <= 10000000 and value not in values:
                values.append(value)

    return values


def extract_bill_amount(text):
    canonical = _canonical_block(text)

    # The OCR service intentionally writes the current amount here.
    raw = _canonical_value(canonical, "BILL AMOUNT")
    value = clean_number(raw)

    if value is not None and 100 <= value <= 10000000:
        return value

    # Also accept the explicit current amount block.
    m = re.search(
        r"---\s*MSEDCL\s+CURRENT\s+BILL\s+AMOUNT\s*---"
        r".*?BILL\s+AMOUNT\s*:\s*₹?\s*([\d,]+(?:\.\d{1,2})?)",
        text or "",
        re.I | re.S,
    )
    if m:
        value = clean_number(m.group(1))
        if value is not None:
            return value

    for line in _lines(text)[:30]:
        if re.search(r"\b\d{1,2}[-/][A-Za-z]{3}[-/]\d{2,4}\b", line, re.I):
            amounts = re.findall(r"(?<![\d])([\d,]+\.\d{2})(?![\d])", line)
            if amounts:
                value = clean_number(amounts[0])
                if value is not None and 100 <= value <= 10000000:
                    return value

    # Some OCR versions split the old payment row into two lines:
    #   "... 07-OCT-20"
    #   "... 710.00"
    # The first money value immediately following the first upper payment
    # date is the current bill amount.
    upper_lines = _lines(text)[:30]
    for i, line in enumerate(upper_lines):
        if re.search(
            r"\b\d{1,2}[-/][A-Za-z]{3}[-/]\d{2,4}\b",
            line,
            re.I,
        ):
            for candidate in upper_lines[i:i + 2]:
                amounts = re.findall(
                    r"(?<![\d])([\d,]+\.\d{2})(?![\d])",
                    candidate,
                )
                if amounts:
                    value = clean_number(amounts[0])
                    if value is not None and 100 <= value <= 10000000:
                        return value

    # Payment box: amount on the DUE DATE row is the current bill amount.
    payment = _payment_box_block(text)
    if payment:
        lines = _lines(payment)

        for i, line in enumerate(lines):
            if re.search(r"\bDUE\s+DATE\b", line, re.I):
                values = _money_values(" ".join(lines[i:i + 2]))
                if values:
                    return values[0]

    # Full OCR explicit labels.
    labels = (
        r"CURRENT\s+BILL\s+AMOUNT",
        r"NET\s+BILL\s+AMOUNT",
        r"TOTAL\s+PAYABLE",
        r"NET\s+PAYABLE",
        r"AMOUNT\s+PAYABLE",
        r"BILL\s+AMOUNT",
    )

    for label in labels:
        m = re.search(
            label + r"\s*[:\-]?\s*₹?\s*([\d,]+(?:\.\d{1,2})?)",
            text or "",
            re.I,
        )
        if m:
            value = clean_number(m.group(1))
            if value is not None and value >= 100:
                return value

    # Strong fallback for this MSEDCL payment-box layout:
    # only accept a monetary value that is clearly separate from the date.
    # Never treat the year in "DUE DATE 23-10-2020" as an amount.
    for i, line in enumerate(_lines(text)[:60]):
        if re.search(r"\bDUE\s+DATE\b", line, re.I):
            # Same line: require a comma-formatted/decimal money token.
            money_tokens = re.findall(
                r"₹?\s*(\d{1,3}(?:,\d{3})+(?:\.\d{1,2})?)",
                line,
            )
            for raw_amount in money_tokens:
                value = clean_number(raw_amount)
                if value is not None and 100 <= value <= 10000000:
                    return value

            # Next line: again require a money-shaped token. This is useful
            # for layouts where OCR puts the amount on its own row.
            if i + 1 < len(_lines(text)[:60]):
                next_line = _lines(text)[:60][i + 1]
                money_tokens = re.findall(
                    r"₹?\s*(\d{1,3}(?:,\d{3})+(?:\.\d{1,2})?)",
                    next_line,
                )
                for raw_amount in money_tokens:
                    value = clean_number(raw_amount)
                    if value is not None and 100 <= value <= 10000000:
                        return value

    return None


