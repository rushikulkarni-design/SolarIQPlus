def extract_bill_month(text):
    current = _current_bill_month_from_text(text)
    if current:
        month, year = current
        return f"{month.title()}-{year}"

    # Header OCR in the supplied bill is damaged. In that case, use the
    # bill date only if we already have a reliable date.
    bill_date = extract_bill_date(text)
    if bill_date:
        try:
            dt = datetime.strptime(bill_date, "%d/%m/%Y")
            return dt.strftime("%b-%Y")
        except ValueError:
            pass

    return None


