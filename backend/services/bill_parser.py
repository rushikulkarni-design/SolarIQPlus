def _normalize_consumer_number(raw):
    if not raw:
        return None

    s = str(raw).strip()

    # Tesseract often reads leading 5 as $, S, or s.
    s = s.replace("$", "5").replace("S", "5").replace("s", "5")
    digits = re.sub(r"\D", "", s)

    # MSEDCL 12-digit consumer numbers in the tested bill are sometimes
    # OCR'd as an 11-digit value beginning with 0.
    if len(digits) == 11 and digits.startswith("0"):
        digits = "5" + digits

    if 10 <= len(digits) <= 14:
        return digits

    return None


def extract_consumer_number(text):
    canonical = _canonical_block(text)

    value = _normalize_consumer_number(
        _canonical_value(canonical, "CONSUMER NUMBER")
    )
    if value:
        return value

    lines = _lines(text)

    for i, line in enumerate(lines):
        m = re.search(
            r"\bConsumer\s+No\.?\s*[:\-]?\s*([0-9$SIlO]{8,16})",
            line,
            re.I,
        )

        if m:
            value = _normalize_consumer_number(m.group(1))
            if value:
                return value

        if re.search(r"\bConsumer\s+No\.?", line, re.I):
            # Label may be separated from value by OCR.
            for nxt in lines[i + 1:i + 3]:
                value = _normalize_consumer_number(nxt)
                if value:
                    return value

    # Only search the upper bill section. This prevents the RTGS beneficiary
    # account number from becoming the consumer number.
    upper = "\n".join(lines[:35])

    candidates = re.findall(
        r"(?<!\d)([0-9$SIlO]{10,16})(?!\d)",
        upper,
        re.I,
    )

    for candidate in candidates:
        value = _normalize_consumer_number(candidate)
        if value and not value.startswith(("19", "20")):
            return value

    return None


