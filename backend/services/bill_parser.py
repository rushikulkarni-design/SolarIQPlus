def parse_bill_fields(raw_text, ocr_confidence=None):
    """
    server.py expects:
        fields, confidence = parse_bill_fields(raw_text, ocr_confidence)
    """
    data = parse_bill(raw_text)

    fields = {
        "consumer_number": data.get("consumer_number"),
        "bill_number": data.get("bill_number"),
        "customer_name": data.get("customer_name"),
        "bill_date": data.get("bill_date"),
        "due_date": data.get("due_date"),
        "monthly_consumption_kwh": data.get("monthly_units"),
        "bill_amount": data.get("bill_amount"),
        "sanctioned_load_kw": data.get("sanctioned_load_kw"),
        "meter_status": data.get("meter_status"),
        "consumer_type": data.get("consumer_type"),
    }

    parser_confidence = data.get("field_confidence") or {}

    try:
        ocr_conf = (
            float(ocr_confidence)
            if ocr_confidence is not None
            else None
        )
    except (TypeError, ValueError):
        ocr_conf = None

    confidence = {}

    for key in FIELD_KEYS:
        value = fields.get(key)

        if value in (None, ""):
            confidence[key] = 0.0
            continue

        level = parser_confidence.get(key)

        if level == "high":
            score = 0.95
        elif level == "medium":
            score = 0.80
        else:
            score = 0.55

        # Do not let the page-level OCR score destroy a strong
        # label-aware/canonical extraction.
        if ocr_conf is not None and level not in ("high",):
            score = max(score, min(0.85, ocr_conf))

        confidence[key] = round(score, 4)

    return fields, confidence


def classify_status(raw_text, fields, confidence):
    """
    Decide whether the bill extraction is usable.

    Core MSEDCL fields are required for a successful extraction.
    Monthly consumption and meter status are optional because many
    MSEDCL HT/industrial bills (including bills with billing-history
    tables) do not expose a single unambiguous current-month value
    or meter-status value in the OCR text.

    We deliberately do NOT invent optional values just to mark the
    extraction as complete.
    """
    core_keys = [
        "consumer_number",
        "bill_number",
        "customer_name",
        "bill_date",
        "due_date",
        "bill_amount",
        "sanctioned_load_kw",
        "consumer_type",
    ]

    missing_core = [
        key for key in core_keys
        if fields.get(key) in (None, "")
    ]

    low_core = [
        key for key in core_keys
        if fields.get(key) not in (None, "")
        and confidence.get(key, 0.0) < 0.60
    ]

    # Optional fields are reported separately by the parser/UI.
    # Their absence must not make an otherwise valid bill fail.
    return "completed" if not missing_core and not low_core else "needs_review"


