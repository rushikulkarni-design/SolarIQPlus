def _canonical_block(text):
    m = re.search(
        r"---\s*MSEDCL\s+CANONICAL\s+OCR\s+FIELDS\s*---"
        r"(.*?)"
        r"---\s*END\s+MSEDCL\s+CANONICAL\s+OCR\s+FIELDS\s*---",
        text or "",
        re.I | re.S,
    )
    return m.group(1) if m else ""


def _targeted_payment_block(text):
    m = re.search(
        r"---\s*MSEDCL\s+TARGETED\s+PAYMENT\s+FIELDS\s*---"
        r"(.*?)"
        r"---\s*END\s+TARGETED\s+PAYMENT\s+FIELDS\s*---",
        text or "",
        re.I | re.S,
    )
    return m.group(1) if m else ""


def _payment_box_block(text):
    m = re.search(
        r"---\s*MSEDCL\s+PAYMENT\s+BOX\s+OCR\s*---"
        r"(.*?)(?=---\s*MSEDCL|\Z)",
        text or "",
        re.I | re.S,
    )
    return m.group(1) if m else ""


def _canonical_value(block, label):
    if not block:
        return None

    m = re.search(
        rf"(?im)^\s*{re.escape(label)}\s*:\s*(.+?)\s*$",
        block,
    )

    return m.group(1).strip() if m else None


