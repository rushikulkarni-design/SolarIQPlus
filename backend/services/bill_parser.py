def detect_bill_format(text: str) -> str:
    """
    Detect the closest known MSEDCL template.

    New/current templates are checked first. Older templates fall back to
    legacy_msedcl. Unknown layouts use generic.
    """
    t = normalize_text(text).upper()

    # Current/new formats — highest priority.
    if "LTIP SOLAR BILL FORMAT" in t or "SOLAR NET METER" in t:
        return "ltip_solar"

    if "HT SOLAR" in t or (
        "SOLAR" in t and ("TOTAL CURRENT BILL" in t or "TOTAL CURRENT BILL (A+B)" in t)
    ):
        return "ht_solar"

    if "OPEN ACCESS" in t and (
        "MS EDCL CD" in t or "BILL FOR OPEN ACCESS" in t or "TOTAL BILL FOR OPEN ACCESS" in t
    ):
        return "ht_open_access"

    if "HT/LTIP E-BILL" in t or "HT/TIP E-BILL" in t or "HT/LTIP" in t:
        return "ht_ltip"

    if "LT BILL FORMAT" in t or "PREPAID CONSUMER BILL" in t:
        return "lt"

    # A newer standard HT image commonly contains these structured sections.
    if "CONSUMPTION TREND" in t and "KVAMD" in t:
        return "ht"

    # Older MSEDCL bills can be heavily Marathi, so OCR may lose
    # "BILLING HISTORY" / "CUSTOMER CARE". Stable header markers are enough.
    if (
        "BILL OF SUPPLY" in t
        or "BILL NO.(GGN)" in t
        or "BILL NO. (GGN)" in t
        or "MAHADISCOM.IN" in t
        or "MSEDCL" in t
    ):
        return "legacy_msedcl"

    return "generic"


def _extract_current_consumption_by_labels(text: str):
    """
    Extract current-month consumption only from a clearly labelled current
    reading/consumption section.

    Billing-history rows are intentionally ignored here. They are handled
    separately only when their month exactly matches the bill month.
    """
    lines = _lines(text)

    strong_label = re.compile(
        r"\b(?:CURRENT\s+MONTH\s+CONSUMPTION|TOTAL\s+CONSUMPTION|"
        r"CURRENT\s+CONSUMPTION|MONTHLY\s+CONSUMPTION)\b",
        re.I,
    )

    for i, line in enumerate(lines):
        if strong_label.search(line):
            # Prefer a number explicitly followed by kWh/units.
            m = re.search(
                r"(\d{1,3}(?:,\d{3})*(?:\.\d+)?)\s*(?:KWH|UNITS?)\b",
                line,
                re.I,
            )
            if m:
                value = clean_number(m.group(1))
                if value is not None and 0 < value <= 1000000:
                    return value

            # Otherwise accept a numeric value on the same labelled line,
            # but reject years and obvious dates.
            nums = re.findall(
                r"(?<![\d/])\d{1,3}(?:,\d{3})*(?:\.\d+)?(?![\d/])",
                line,
            )
            candidates = [
                clean_number(n) for n in nums
                if clean_number(n) is not None
                and 0 < clean_number(n) <= 1000000
            ]
            candidates = [
                n for n in candidates
                if n < 100000
            ]
            if candidates:
                return candidates[-1]

            if i + 1 < len(lines):
                m = re.search(
                    r"(\d{1,3}(?:,\d{3})*(?:\.\d+)?)\s*(?:KWH|UNITS?)\b",
                    lines[i + 1],
                    re.I,
                )
                if m:
                    value = clean_number(m.group(1))
                    if value is not None and 0 < value <= 1000000:
                        return value

    # Current/previous/MF/consumption table. Only accept a numeric row when
    # the header itself explicitly identifies the consumption column.
    for i, line in enumerate(lines):
        if (
            re.search(r"\bCURRENT\b", line, re.I)
            and re.search(r"\bPREVIOUS\b", line, re.I)
            and re.search(r"\bCONSUMPTION\b", line, re.I)
        ):
            for candidate in lines[i + 1:i + 4]:
                nums = re.findall(
                    r"(?<![\d/])\d{1,3}(?:,\d{3})*(?:\.\d+)?(?![\d/])",
                    candidate,
                )
                if len(nums) >= 4:
                    value = clean_number(nums[3])
                    if value is not None and 0 < value <= 1000000:
                        return value

    # LT green table: current reading / previous reading / MF / consumption.
    for i, line in enumerate(lines):
        if re.search(
            r"\b(?:CURRENT\s+READING|CURRENT\s+READINGS)\b",
            line,
            re.I,
        ):
            for candidate in lines[i + 1:i + 4]:
                nums = re.findall(
                    r"(?<![\d/])\d{1,3}(?:,\d{3})*(?:\.\d+)?(?![\d/])",
                    candidate,
                )
                if len(nums) >= 4:
                    value = clean_number(nums[3])
                    if value is not None and 0 < value <= 1000000:
                        return value

    return None


def _generic_parse(text: str):
    """
    Unknown-format safety net.

    Only return the three fields we can reasonably locate without knowing
    the template. Never manufacture dates, bill amounts, or load values.
    """
    return {
        "consumer_number": extract_consumer_number(text),
        "bill_number": None,
        "customer_name": extract_customer_name(text),
        "bill_date": None,
        "due_date": None,
        "monthly_units": _extract_current_consumption_by_labels(text),
        "bill_amount": None,
        "sanctioned_load_kw": None,
        "meter_status": None,
        "consumer_type": None,
        "is_ht": False,
        "solar_connection": False,
        "solar_capacity": None,
        "solar_meter": False,
    }


def _parse_known_format(text: str, format_name: str):
    """
    One common extraction core for the known templates.

    The separate functions below make the format-specific architecture
    explicit and give us a clean place to add layout-specific rules later.
    """
    data = _parse_legacy_bill(text)

    # Current-month units are especially important for LT/LTIP/solar layouts.
    current_units = _extract_current_consumption_by_labels(text)
    if current_units is not None:
        data["monthly_units"] = current_units

    if format_name in ("ltip_solar", "ht_solar"):
        data["solar_connection"] = True
        data["solar_meter"] = True

    if format_name in ("ht", "ht_ltip", "ht_open_access", "ht_solar"):
        data["is_ht"] = True
        if not data.get("consumer_type"):
            data["consumer_type"] = "Industrial"

    data["detected_format"] = format_name
    return data



