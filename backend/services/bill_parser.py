def extract_customer_name(text):
    lines = _lines(text)

    for i, line in enumerate(lines):
        m = re.search(
            r"\b(?:Customer|Consumer)\s+Name\s*[:\-]?\s*(.+)$",
            line,
            re.I,
        )

        if m:
            name = m.group(1).strip(" :-")
            name = re.split(
                r"\b(?:Address|Mobile|Meter\s+No|Email)\b",
                name,
                maxsplit=1,
                flags=re.I,
            )[0].strip()
            name = re.sub(r"\s+", " ", name)

            if len(name) >= 3:
                return name

        if re.search(r"\b(?:MR|MRS|MS|SMT)\.?\s+[A-Z]", line, re.I):
            candidate = re.split(
                r"\b(?:Um|CEPA|SNO|SN|FLAT|ADDRESS|PLOT|ROAD|PUNE|MUMBAI)\b",
                line, maxsplit=1, flags=re.I
            )[0].strip(" :-")
            if len(candidate) >= 5:
                return re.sub(r"\s+", " ", candidate)

        if re.search(r"\b(?:Customer|Consumer)\s+Name\s*:?\s*$", line, re.I):
            if i + 1 < len(lines):
                name = re.split(
                    r"\b(?:Address|Mobile|Meter\s+No|Email)\b",
                    lines[i + 1],
                    maxsplit=1,
                    flags=re.I,
                )[0].strip()

                if len(name) >= 3:
                    return name

    return None


