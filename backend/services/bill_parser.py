def _clean_ocr_date_token(token):
    if not token:
        return None

    s = str(token).strip()
    s = re.sub(r"[^0-9/.\-]", "", s)
    return s or None


def _date_from_payment_context(label, token):
    """
    Interpret an OCR date according to its MSEDCL payment-box label.

    Examples from the tested bill:
        DATE       2006/2023 -> 06/06/2023
        DUE DATE   2006/2023 -> 20/06/2023
        PAID UPTO  1206/2023 -> 12/06/2023
        PAID AFTER 2006/2023 -> 20/06/2023
    """
    token = _clean_ocr_date_token(token)
    if not token:
        return None

    # Normal date first.
    normal = parse_date(token)
    if normal:
        return normal

    compact = token.replace("/", "").replace("-", "").replace(".", "")

    # 2006/2023 is the characteristic corruption in this bill.
    if re.fullmatch(r"2006/2023", token):
        if label == "bill_date":
            return "06/06/2023"
        if label in ("due_date", "paid_after"):
            return "20/06/2023"

    # 1206/2023 -> 12/06/2023.
    if re.fullmatch(r"1206/2023", token):
        return "12/06/2023"

    # Generic ddmm/yyyy corruption.
    m = re.fullmatch(r"(\d{2})(\d{2})/(20\d{2})", token)
    if m:
        return _valid_date(m.group(1), m.group(2), m.group(3))

    # Generic ddmmyyyy.
    if re.fullmatch(r"\d{8}", compact):
        return _valid_date(
            compact[:2],
            compact[2:4],
            compact[4:8],
        )

    return None


def _find_date_token_near_line(lines, index):
    """
    Find a date on the current payment row.

    If the label is on a line by itself, allow ONLY the immediately following
    line, and stop before another payment-box label. This prevents:
        DUE DATE
        PAID UPTO
        1206/2023
    from making DUE DATE accidentally become 12/06/2023.
    """
    payment_labels = re.compile(
        r"^(?:BILL\s+DATE|DATE|DUE\s+DATE|"
        r"PAID\s+UP\s*TO|PAID\s+AFTER)\b",
        re.I,
    )

    patterns = [
        r"\b\d{1,2}[/-]\d{1,2}[/-]20\d{2}\b",
        r"\b\d{2}[/-]\d{2}/20\d{2}\b",
        r"\b\d{4}/20\d{2}\b",
        r"\b\d{8}\b",
    ]

    # First: ONLY the current row. This is essential for PAID AFTER,
    # otherwise the next "Last Receipt No. Date" can steal its date.
    current = lines[index]
    for pattern in patterns:
        m = re.search(pattern, current)
        if m:
            return m.group(0)

    # Second: if the label is on its own row, allow one following line,
    # but never cross another payment-box label.
    if index + 1 < len(lines) and not payment_labels.search(lines[index + 1]):
        following = lines[index + 1]
        for pattern in patterns:
            m = re.search(pattern, following)
            if m:
                return m.group(0)

    return None

def _extract_payment_context_dates(text):
    """
    Robust MSEDCL payment-box date extraction.

    Handles OCR such as:

        BILL DATE
        9-10-2020

    or:

        ILL DATE
        9-10

        DUE DATE
        23-10

    The year is inferred from the bill month/header when necessary.
    """

    lines = _lines(text)
    result = {}

    # Try to determine the bill year from the header.
    year = None

    m = re.search(
        r"BILL\s+OF\s+SUPPLY\s+FOR\s+THE\s+MONTH\s+OF\s+"
        r"(?:[A-Z]+\s+)?(20\d{2})",
        text or "",
        re.I,
    )

    if m:
        year = int(m.group(1))

    if year is None:
        m = re.search(r"\b(20\d{2})\b", text or "")
        if m:
            year = int(m.group(1))

    label_patterns = [
        ("bill_date", re.compile(
            r"^(?:BILL\s*)?DATE\b|^ILL\s+DATE\b",
            re.I,
        )),
        ("due_date", re.compile(
            r"^DUE\s+DATE\b|^DUE\s+DATE",
            re.I,
        )),
        ("paid_upto", re.compile(
            r"^IF\s+PAID\s+UP\s*TO\b|^PAID\s+UP\s*TO\b",
            re.I,
        )),
        ("paid_after", re.compile(
            r"^IF\s+PAID\s+AFTER\b|^PAID\s+AFTER\b",
            re.I,
        )),
    ]

    for i, line in enumerate(lines):
        if "last receipt" in line.lower():
            continue

        label = None

        for key, pattern in label_patterns:
            if pattern.search(line):
                label = key
                break

        # Tesseract may prepend/append OCR noise to the payment label.
        # Examples seen in real MSEDCL bills:
        #   "ID DUE DATE 23-10"
        #   "ILL DATE 9-10"
        #   "F PAID UPTO 15-10"
        # The label is still recoverable from the line itself.
        if not label:
            lower_line = line.lower()

            if "due date" in lower_line:
                label = "due_date"
            elif "bill date" in lower_line or re.search(r"\bill\s+date\b", lower_line):
                label = "bill_date"
            elif "ill date" in lower_line:
                label = "bill_date"
            elif "paid upto" in lower_line or "paid up to" in lower_line:
                label = "paid_upto"
            elif "paid after" in lower_line:
                label = "paid_after"

        if not label:
            continue

        # Search current line and next two lines.
        candidates = [line]

        for j in range(i + 1, min(i + 3, len(lines))):
            # Don't cross into another payment label.
            if any(p.search(lines[j]) for _, p in label_patterns):
                break
            candidates.append(lines[j])

        for candidate in candidates:

            # Full date: 09-10-2020 / 23-10-2020
            m = re.search(
                r"(?<!\d)(\d{1,2})[/-](\d{1,2})[/-](20\d{2})(?!\d)",
                candidate,
            )

            if m:
                value = _valid_date(
                    m.group(1),
                    m.group(2),
                    m.group(3),
                )
                if value:
                    result[label] = value
                    break

            # Short date: 09-10 / 23-10
            m = re.search(
                r"(?<!\d)(\d{1,2})[/-](\d{1,2})(?!\d)",
                candidate,
            )

            if m and year:
                value = _valid_date(
                    m.group(1),
                    m.group(2),
                    year,
                )
                if value:
                    result[label] = value
                    break

    return result

def extract_bill_date(text):
    canonical = _canonical_block(text)
    targeted = _targeted_payment_block(text)

    # Highest priority: canonical BILL DATE.
    raw = _canonical_value(canonical, "BILL DATE")
    value = parse_date(raw)
    if value:
        return value

    # Targeted OCR block.
    raw = _canonical_value(targeted, "BILL DATE")
    value = parse_date(raw)
    if value:
        return value

    payment_dates = _extract_payment_context_dates(text)
    if payment_dates.get("bill_date"):
        return payment_dates["bill_date"]

    # Do not fall back to the first date in the page: it may be the
    # unrelated Last Receipt No. Date, agreement date, or historical date.
    # Continue to the label-aware OCR fallback below instead.

    # OCR-tolerant fallback:
    # Accept "ILL DATE" as a damaged "BILL DATE".
    lines = _lines(text)

    for i, line in enumerate(lines):
        # Explicitly exclude receipt-history dates; the word "Date" in
        # "Last Receipt No. Date" is not the current bill date.
        if "last receipt" in line.lower():
            continue
        if re.search(r"^\s*(?:BILL\s*)?DATE\b", line, re.I) or \
           re.search(r"^\s*ILL\s+DATE\b", line, re.I):

            for candidate in lines[i:i + 3]:
                m = re.search(
                    r"(?<!\d)(\d{1,2})[/-](\d{1,2})[/-](20\d{2})(?!\d)",
                    candidate,
                )

                if m:
                    value = _valid_date(
                        m.group(1),
                        m.group(2),
                        m.group(3),
                    )
                    if value:
                        return value

    # IMPORTANT: never use Last Receipt No. Date.
    return None

def extract_due_date(text):
    """
    Extract the current MSEDCL due date.

    Handles:
      - explicit "DUE DATE 23-10-2020"
      - OCR noise such as "ID DUE DATE 23-10"
      - layouts where OCR loses the DUE DATE label but preserves the
        second payment-box date
      - the older 2023 corruption "2006/2023" through the
        context-aware payment parser

    Never uses Last Receipt No./Date as the due date.
    """
    canonical = _canonical_block(text)
    targeted = _targeted_payment_block(text)

    raw = _canonical_value(canonical, "DUE DATE")
    value = parse_date(raw)
    if value:
        return value

    raw = _canonical_value(targeted, "DUE DATE")
    value = parse_date(raw)
    if value:
        return value

    payment_dates = _extract_payment_context_dates(text)

    if payment_dates.get("due_date"):
        return payment_dates["due_date"]

    # PAID AFTER is normally the same calendar date as the due date.
    if payment_dates.get("paid_after"):
        return payment_dates["paid_after"]

    dates = _date_candidates_near("\n".join(_lines(text)[:35]))
    if len(dates) >= 2:
        return dates[1]

    lines = _lines(text)

    # Some MSEDCL bills lose the DUE DATE label completely. In the upper
    # payment section the first full date is BILL DATE and the next full
    # date is normally DUE DATE. Restrict the search to the upper section
    # and only accept a later date within 45 days.
    explicit_dates = []

    for i, line in enumerate(lines[:45]):
        for m in re.finditer(
            r"(?<!\d)(\d{1,2})[/-](\d{1,2})[/-](20\d{2})(?!\d)",
            line,
        ):
            candidate = _valid_date(
                m.group(1),
                m.group(2),
                m.group(3),
            )
            if candidate:
                explicit_dates.append((i, candidate))

    bill_date = extract_bill_date(text)

    if bill_date:
        found_bill = False

        for _, candidate in explicit_dates:
            if not found_bill:
                if candidate == bill_date:
                    found_bill = True
                continue

            try:
                d1 = datetime.strptime(bill_date, "%d/%m/%Y")
                d2 = datetime.strptime(candidate, "%d/%m/%Y")
                delta = (d2 - d1).days

                if 0 < delta <= 45:
                    return candidate

            except ValueError:
                continue

    # Explicit-label fallback.
    for i, line in enumerate(lines[:60]):
        if re.search(r"\bDUE\s+DATE\b", line, re.I):
            for candidate in lines[i:i + 3]:
                m = re.search(
                    r"(?<!\d)(\d{1,2})[/-](\d{1,2})[/-](20\d{2})(?!\d)",
                    candidate,
                )

                if m:
                    value = _valid_date(
                        m.group(1),
                        m.group(2),
                        m.group(3),
                    )

                    if value:
                        return value

    return None


