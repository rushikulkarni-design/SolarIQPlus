def parse_bill(text):
    """
    Main dispatcher.

    Current/new MSEDCL formats are handled before historical layouts.
    Unknown layouts intentionally return only safe generic fields.
    """
    text = normalize_text(text)
    format_name = detect_bill_format(text)

    parsers = {
        "lt": _parse_lt,
        "ltip_solar": _parse_ltip_solar,
        "ht": _parse_ht,
        "ht_ltip": _parse_ht_ltip,
        "ht_open_access": _parse_ht_open_access,
        "ht_solar": _parse_ht_solar,
        "legacy_msedcl": _parse_legacy_msedcl,
    }

    if format_name == "generic":
        data = _generic_parse(text)
        data["detected_format"] = "generic"
    else:
        data = parsers[format_name](text)

    data.setdefault("detected_format", format_name)

    # Keep the existing API's confidence behavior.
    data["field_confidence"] = _field_confidence(data, text)
    data["confidence"] = data["field_confidence"]
    return data


