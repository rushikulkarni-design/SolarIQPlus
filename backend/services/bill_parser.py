def extract_bill_number(text):
    """
    Extract an MSEDCL bill number without confusing it with the consumer
    number, beneficiary account number, phone number, or other long numbers.

    Priority:
      1. Canonical OCR field.
      2. Explicit BILL NO / BILL NUMBER label.
      3. A standalone long numeric value immediately below the
         "BILL OF SUPPLY FOR THE MONTH OF ..." header.
      4. Modern split-header number such as "2023065670 10606".
    """
    canonical = _canonical_block(text)

    # 1. Canonical OCR field has highest priority.
    raw = _canonical_value(canonical, "BILL NUMBER")
    if raw:
        digits = re.sub(r"\D", "", raw)
        if 8 <= len(digits) <= 20:
            return digits

    t = normalize_text(text)
    lines = _lines(t)

    # 2. Explicit labels.
    patterns = [
        r"\bBILL\s*NO\.?\s*\(\s*GGN\s*\)\s*[:\-]?\s*([0-9]{8,20})",
        r"\bBILL\s*NO\.?\s*[:\-]?\s*([0-9]{8,20})",
        r"\bBILL\s*NUMBER\s*[:\-]?\s*([0-9]{8,20})",
        r"\bBILL\s*NO\s*\(GGN\)\s*[:\-]?\s*([0-9]{8,20})",
    ]

    for pattern in patterns:
        m = re.search(pattern, t, re.I)
        if m:
            return re.sub(r"\D", "", m.group(1))

    # 3. Older/HT-LTIP MSEDCL bills frequently put the bill number alone
    # on the next line immediately after the month header:
    #
    # BILL OF SUPPLY FOR THE MONTH OF Oct 2020
    # 000000949750685
    #
    # Restrict this search to the first ~20 lines so that RTGS account
    # numbers and billing-history values cannot be selected.
    for i, line in enumerate(lines[:25]):
        if re.search(
            r"BILL\s+OF\s+SUPPLY\s+FOR\s+THE\s+MONTH\s+OF",
            line,
            re.I,
        ):
            for candidate in lines[i + 1:i + 5]:
                digits = re.sub(r"\D", "", candidate)
                if (
                    re.fullmatch(r"\d{10,20}", digits or "")
                    and not digits.startswith(("001840", "490110"))
                ):
                    return digits

    # 4. Modern header numbers can be OCR'd as two adjacent groups:
    # 2023065670 10606
    header = re.search(
        r"(?is)BILL\s+OF\s+SUPPLY.{0,900}",
        t,
    )
    search_text = header.group(0) if header else t[:1800]

    candidates = []

    for m in re.finditer(
        r"(?<!\d)(20\d{6,})\s+(\d{4,8})(?!\d)",
        search_text,
    ):
        value = m.group(1) + m.group(2)
        if 8 <= len(value) <= 20:
            candidates.append(value)

    for m in re.finditer(
        r"(?<!\d)(20\d{9,18})(?!\d)",
        search_text,
    ):
        candidates.append(m.group(1))

    if candidates:
        return list(dict.fromkeys(candidates))[0]

    return None


