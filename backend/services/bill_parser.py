"""
SolarIQ+ - MSEDCL electricity-bill parser
=========================================

Deterministic, OCR-tolerant parser for the MSEDCL bill formats used by
SolarIQ+.

Important design rules:
1. Prefer the canonical OCR block generated by ocr_service.py.
2. Never use "Last Receipt No. Date" as the bill date.
3. Treat the payment box as:
      DATE / BILL DATE  -> current bill date
      DUE DATE           -> current due date
      IF PAID UPTO       -> early-payment date/amount
      IF PAID AFTER      -> late-payment date/amount
4. Handle common Tesseract corruption such as:
      06/06/2023 -> 2006/2023
      20/06/2023 -> 2006/2023
      12/06/2023 -> 1206/2023
5. For the supplied May-2023 HT MSEDCL sample, the expected important
   values are:
      consumer number : 502039075170
      bill number     : 202306567010606
      customer name   : Renuko Mate Mane Bachat Gat
      bill date       : 06/06/2023
      due date        : 20/06/2023
      bill amount     : 93960.0
      sanctioned load : 135.0 kW
      consumer type   : Industrial
6. Do not invent current monthly consumption when the bill does not expose
   it clearly. Billing-history values are NOT automatically the current
   month's consumption.
"""

import re
from datetime import datetime
from typing import Optional


