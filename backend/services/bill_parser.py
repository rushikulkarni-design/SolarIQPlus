def _parse_ltip_solar_current(text):
    """
    Dedicated parser for the current LT/IP Solar Net Meter layout.

    This format is visually/structurally different from the standard
    MSEDCL LT/HT bill.  Do not run the generic legacy extraction first,
    because that can confuse the solar agreement date, receipt dates,
    customer-care numbers, and billing-history values with current fields.
    """
    t = normalize_text(text)
    lines = _lines(t)

    data = {
        "consumer_number": None,
        "bill_number": None,
        "customer_name": None,
        "bill_date": None,
        "due_date": None,
        "monthly_units": None,
        "bill_amount": None,
        "sanctioned_load_kw": None,
        "meter_status": None,
        "consumer_type": None,
        "is_ht": False,
        "solar_connection": True,
        "solar_capacity": None,
        "solar_meter": True,
        "gstin": None,
        "bill_month": None,
    }

    # Consumer number: prefer explicit customer/consumer number label.
    data["consumer_number"] = extract_consumer_number(t)

    # Current solar format bill number.
    m = re.search(
        r"BILL\s*NO\.?\s*\(GGN\)\s*[:\-]?\s*(\d{10,20})",
        t,
        re.I,
    )
    if m:
        data["bill_number"] = m.group(1)

    if not data["bill_number"]:
        m = re.search(r"\bBILL\s*NO\.?\s*[:\-]?\s*(\d{10,20})", t, re.I)
        if m:
            data["bill_number"] = m.group(1)

    # Customer name in the current solar layout is often unlabeled.
    # The first explicit date is the bill date, and the name is normally
    # immediately below that date.
    if not data["customer_name"]:
        for i, line in enumerate(lines[:35]):
            if re.fullmatch(r"\d{1,2}[/-]\d{1,2}[/-]20\d{2}", line):
                for candidate in lines[i + 1:i + 4]:
                    if (
                        len(candidate) >= 5
                        and not re.search(
                            r"\b(?:BILL|DUE|PAID|SOLAR|GSTIN|ADDRESS|VILLAGE|"
                            r"MOBILE|EMAIL|METER|DATE|AGREEMENT|KW|RS)\b",
                            candidate,
                            re.I,
                        )
                        and not re.fullmatch(r"[\d\s.,:/()\-]+", candidate)
                        and not re.search(r"\d{3,}", candidate)
                    ):
                        data["customer_name"] = candidate
                        break
                if data["customer_name"]:
                    break

    # Fallback: labelled name.
    if not data["customer_name"]:
        data["customer_name"] = extract_customer_name(t)

    # Current solar bill has the bill date and due date in the top-right
    # payment boxes. The labels may be lost by OCR, so use the first two
    # explicit dates in the upper bill section. Do NOT search for a bare
    # "DATE" substring because "SOLAR AGREEMENT DATE" occurs later.
    top = "\n".join(lines[:35])
    dates = _date_candidates_near(top)

    if len(dates) >= 1:
        data["bill_date"] = dates[0]
    if len(dates) >= 2:
        data["due_date"] = dates[1]

    # Current bill amount sits immediately after the due-date row in this
    # template. Prefer the first currency amount in the 3 lines after the
    # second date. This avoids treating "3.00 KW" as the bill amount.
    if len(dates) >= 2:
        second_date_index = None
        seen = 0
        for i, line in enumerate(lines[:35]):
            if re.fullmatch(r"\d{1,2}[/-]\d{1,2}[/-]20\d{2}", line):
                seen += 1
                if seen == 2:
                    second_date_index = i
                    break

        if second_date_index is not None:
            for candidate in lines[second_date_index + 1:second_date_index + 4]:
                amounts = re.findall(
                    r"(?<!\d)(\d{1,3}(?:,\d{3})*\.\d{2})(?!\d)",
                    candidate,
                )
                if amounts:
                    data["bill_amount"] = clean_number(amounts[0])
                    break

    # If the payment-box labels survived OCR, use an explicitly labelled
    # date only when the label is at the beginning of the line.
    m = re.search(
        r"(?im)^\s*(?:BILL\s+DATE|DATE)\s*[:\-]\s*"
        r"(\d{1,2}[/-]\d{1,2}[/-]20\d{2})\s*$",
        t,
    )
    if m:
        data["bill_date"] = parse_date(m.group(1)) or data["bill_date"]

    m = re.search(
        r"(?im)^\s*DUE\s+DATE\s*[:\-]\s*"
        r"(\d{1,2}[/-]\d{1,2}[/-]20\d{2})\s*$",
        t,
    )
    if m:
        data["due_date"] = parse_date(m.group(1)) or data["due_date"]

    # Final fallback for amount: only lines containing an amount-like value
    # in the upper payment section, excluding KW/load lines.
    if data["bill_amount"] is None:
        for line in lines[:30]:
            if re.search(r"\b(?:KW|LOAD|AGREEMENT|SECURITY|METER)\b", line, re.I):
                continue
            amounts = re.findall(
                r"(?<!\d)(\d{1,3}(?:,\d{3})*\.\d{2})(?!\d)",
                line,
            )
            if amounts:
                data["bill_amount"] = clean_number(amounts[0])
                break

    # Sanctioned load / solar capacity: current layout exposes 3.00 KW.
    m = re.search(
        r"(?:Sanctioned|Approved|मंजूर)\s*(?:Load|भार)?\s*"
        r"[:\-]?\s*([\d,.]+)\s*KW",
        t,
        re.I,
    )
    if m:
        data["sanctioned_load_kw"] = clean_number(m.group(1))

    if data["sanctioned_load_kw"] is None:
        # OCR often preserves just "3.00 KW" near the solar/load section.
        for line in lines:
            if re.search(r"KW", line, re.I):
                vals = re.findall(r"(?<![\d.])\d+(?:\.\d+)?", line)
                for v in vals:
                    n = clean_number(v)
                    if n is not None and 0 < n <= 100:
                        data["sanctioned_load_kw"] = n
                        break
                if data["sanctioned_load_kw"] is not None:
                    break

    # Solar capacity is explicitly shown in the current solar format.
    m = re.search(
        r"(?:SOLAR\s+(?:NET\s+METER|GENERATION|CAPACITY)|SOLAR\s+NET\s+METER)"
        r".{0,80}?(\d+(?:\.\d+)?)\s*KW",
        t,
        re.I | re.S,
    )
    if m:
        data["solar_capacity"] = clean_number(m.group(1))
    elif data["sanctioned_load_kw"] is not None:
        data["solar_capacity"] = data["sanctioned_load_kw"]

    # Current units: use the explicit Import row's Consumption column.
    # For net-meter bills this is more meaningful than the green "Total"
    # box, which may be zero after solar offset.
    m = re.search(
        r"\bImport\b\s+(\d{2,7})\s+(\d{2,7})\s+"
        r"(\d+(?:\.\d+)?)\s+(\d{1,7})(?!\d)",
        t,
        re.I,
    )
    if m:
        data["monthly_units"] = clean_number(m.group(4))

    if data["monthly_units"] is None:
        # OCR may place "Current Readings / Previous Readings / MF /
        # Consumption" on separate lines. Look for the first Import row.
        for i, line in enumerate(lines):
            if re.search(r"^Import\b", line, re.I):
                nums = re.findall(
                    r"(?<![\d/])\d+(?:\.\d+)?(?![\d/])",
                    line,
                )
                if len(nums) >= 4:
                    data["monthly_units"] = clean_number(nums[-1])
                    break
                for candidate in lines[i + 1:i + 3]:
                    nums = re.findall(
                        r"(?<![\d/])\d+(?:\.\d+)?(?![\d/])",
                        candidate,
                    )
                    if len(nums) >= 4:
                        data["monthly_units"] = clean_number(nums[-1])
                        break
                if data["monthly_units"] is not None:
                    break

    # Meter status is explicit in the sample.
    m = re.search(r"Meter\s+Status\s*:\s*([A-Za-z]+)", t, re.I)
    if m:
        data["meter_status"] = m.group(1).strip().title()

    # Consumer type from the tariff line.
    if re.search(r"\b(?:Res|Residential)\b", t, re.I):
        data["consumer_type"] = "Residential"
    elif re.search(r"\b(?:Comm|Commercial)\b", t, re.I):
        data["consumer_type"] = "Commercial"
    elif re.search(r"\b(?:Ind|Industrial)\b", t, re.I):
        data["consumer_type"] = "Industrial"

    return data


