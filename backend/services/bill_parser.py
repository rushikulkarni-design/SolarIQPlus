def _field_confidence(data, raw_text):
    text = raw_text or ""
    canonical = _canonical_block(text)
    targeted = _targeted_payment_block(text)
    payment_dates = _extract_payment_context_dates(text)
    is_legacy = detect_bill_format(text) == "legacy_msedcl"

    result = {}

    def assign(key, value, high=False, medium=False):
        if value in (None, ""):
            result[key] = "low"
        elif high:
            result[key] = "high"
        elif medium:
            result[key] = "medium"
        else:
            result[key] = "low"

    assign(
        "consumer_number",
        data.get("consumer_number"),
        high=bool(_canonical_value(canonical, "CONSUMER NUMBER")),
        medium=bool(re.search(r"Consumer\s+No", text, re.I))
        or (is_legacy and bool(data.get("consumer_number"))),
    )

    assign(
        "bill_number",
        data.get("bill_number"),
        high=bool(_canonical_value(canonical, "BILL NUMBER")),
        medium=bool(re.search(r"BILL\s+OF\s+SUPPLY", text, re.I))
        or (is_legacy and bool(data.get("bill_number"))),
    )

    assign(
        "customer_name",
        data.get("customer_name"),
        high=bool(re.search(r"(?:Customer|Consumer)\s+Name", text, re.I)),
        medium=is_legacy and bool(data.get("customer_name")),
    )

    assign(
        "bill_date",
        data.get("bill_date"),
        high=bool(_canonical_value(canonical, "BILL DATE")),
        medium=bool(
            _canonical_value(targeted, "BILL DATE")
            or payment_dates.get("bill_date")
            or (is_legacy and data.get("bill_date"))
        ),
    )

    assign(
        "due_date",
        data.get("due_date"),
        high=bool(_canonical_value(canonical, "DUE DATE")),
        medium=bool(
            _canonical_value(targeted, "DUE DATE")
            or payment_dates.get("due_date")
            or payment_dates.get("paid_after")
            or (is_legacy and data.get("due_date"))
        ),
    )

    assign(
        "monthly_units",
        data.get("monthly_units"),
        high=bool(re.search(
            r"Total\s+Consumption|Monthly\s+Consumption|Current\s+Consumption",
            text,
            re.I,
        )),
    )

    assign(
        "bill_amount",
        data.get("bill_amount"),
        high=bool(
            _canonical_value(canonical, "BILL AMOUNT")
            or re.search(
                r"---\s*MSEDCL\s+CURRENT\s+BILL\s+AMOUNT",
                text,
                re.I,
            )
        ),
        medium=bool(re.search(
            r"DUE\s+DATE|BILL\s+AMOUNT|TOTAL\s+PAYABLE",
            text,
            re.I,
        )) or (is_legacy and bool(data.get("bill_amount"))),
    )

    assign(
        "sanctioned_load_kw",
        data.get("sanctioned_load_kw"),
        high=bool(re.search(r"Sanctioned\s+Load", text, re.I)),
        medium=is_legacy and bool(data.get("sanctioned_load_kw")),
    )

    assign(
        "meter_status",
        data.get("meter_status"),
        high=bool(re.search(r"Meter\s+Status", text, re.I)),
        medium=is_legacy and bool(data.get("meter_status")),
    )

    assign(
        "consumer_type",
        data.get("consumer_type"),
        high=bool(re.search(
            r"\bINDUSTRIAL\b|\bCOMMERCIAL\b|\bRESIDENTIAL\b",
            text,
            re.I,
        )),
    )

    return result


