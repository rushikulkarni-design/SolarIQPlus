def extract_sanctioned_load(text):
    t = normalize_text(text)

    patterns = (
        # Normal OCR
        r"Sanctioned\s+Load\s*\(KW\)\s*[:\-]?\s*([\d,.]+)",
        
        # OCR may lose first character: "anctioned load"
        r"(?:S)?anctioned\s+Load\s*(?:\(KW\))?\s*[:\-]?\s*([\d,.]+)",
        
        # Abbreviated form
        r"Sanct\.?\s*Load\s*(?:\(KW\))?\s*[:\-]?\s*([\d,.]+)",
    )

    for pattern in patterns:
        m = re.search(pattern, t, re.I)
        if m:
            value = clean_number(m.group(1))
            if value is not None and 0 < value <= 10000:
                return value

    for line in _lines(t)[:35]:
        if re.search(r"\bKW\b", line, re.I):
            for raw in re.findall(r"(?<![\d.])\d+(?:\.\d+)?", line):
                value = clean_number(raw)
                if value is not None and 0 < value <= 1000 and "." in raw:
                    return value

    return None

def extract_meter_status(text):
    m = re.search(
        r"\bMeter\s+Status\s*[:\-]?\s*([A-Za-z]+)",
        text or "",
        re.I,
    )

    if m:
        return m.group(1).strip().title()

    for line in _lines(text)[:80]:
        cleaned = re.sub(r"[^A-Za-z]", "", line)
        if cleaned.upper() == "NORMAL":
            return "Normal"

    return None


def detect_consumer_type(text):
    upper = (text or "").upper()

    if (
        "INDUSTRIAL" in upper
        or "INDUSTRY" in upper
        or "LTIP" in upper
        or "HT4A" in upper
        or "SUPPLY AT: HT" in upper
        or "LT INDUSTRY" in upper
    ):
        return "Industrial"

    if "COMMERCIAL" in upper:
        return "Commercial"

    if "RESIDENTIAL" in upper or "LT RES" in upper:
        return "Residential"

    return None


def detect_ht(text):
    upper = (text or "").upper()

    return bool(
        re.search(
            r"\bHT4A\b|\bHT\s+CONSUMER\b|\bSUPPLY\s+AT\s*:\s*HT\b",
            upper,
        )
    )


