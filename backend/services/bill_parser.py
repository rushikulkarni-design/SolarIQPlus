def _extract_explicit_current_consumption(text):
    """
    Only return consumption when the OCR explicitly labels it as current.
    """
    patterns = (
        r"(?:Total\s+Consumption|Monthly\s+Consumption|"
        r"Current\s+Consumption|Current\s+Month\s+Consumption)"
        r"\s*[:\-]?\s*([\d,]+(?:\.\d+)?)\s*(?:kWh|units?)?",
        r"\bConsumption\s*\(?(?:kWh|Units?)\)?\s*[:\-]?\s*"
        r"([\d,]+(?:\.\d+)?)",
    )

    for pattern in patterns:
        m = re.search(pattern, text or "", re.I)
        if m:
            value = clean_number(m.group(1))
            if value is not None and 0 < value <= 1000000:
                return value

    return None


def _current_bill_month_from_text(text):
    """
    Extract the current bill month from the header when OCR got the month.
    """
    m = re.search(
        r"SUPPLY\s+FOR\s+THE\s+MONTH\s+OF\s+"
        r"(JAN|FEB|MAR|APR|MAY|JUN|JUL|AUG|SEP|OCT|NOV|DEC)"
        r"[A-Z .\-]*(20\d{2})",
        text or "",
        re.I,
    )

    if m:
        return m.group(1).upper(), int(m.group(2))

    return None


def _extract_history_rows(text):
    """
    Parse billing-history rows of the form:

        APR-23  5,709  112  1,20,649

    Returns (month, year, units, demand, amount).
    """
    rows = []

    month_re = (
        r"(?P<month>JAN|FEB|MAR|APR|MAY|JUN|JUL|AUG|SEP|OCT|NOV|DEC)"
        r"[\s.\-]*(?P<year>2[0-9])\b"
    )

    for line in _lines(text):
        m = re.search(month_re, line, re.I)
        if not m:
            continue

        rest = line[m.end():]

        nums = re.findall(
            r"(?<![\d/])\d{1,3}(?:,\d{3})*(?:\.\d+)?(?![\d/])",
            rest,
        )

        if len(nums) < 1:
            continue

        values = [clean_number(x) for x in nums]
        values = [x for x in values if x is not None]

        if not values:
            continue

        units = values[0]
        demand = values[1] if len(values) >= 2 else None
        amount = values[2] if len(values) >= 3 else None

        rows.append(
            (
                m.group("month").upper(),
                2000 + int(m.group("year")),
                units,
                demand,
                amount,
            )
        )

    return rows


def extract_monthly_consumption(text):
    """
    Extract a reliable current-month consumption value.

    Priority:
      1. Explicit current/monthly/total consumption label.
      2. A billing-history row that exactly matches the bill month.

    We NEVER use the latest historical row merely because it is nearby.
    For example, an Oct-2020 bill whose history starts with Sep-2020 must
    not report Sep-2020 consumption as Oct-2020 consumption.
    """
    explicit = _extract_explicit_current_consumption(text)
    if explicit is not None:
        return explicit

    current = _current_bill_month_from_text(text)
    if current:
        current_month, current_year = current
        rows = _extract_history_rows(text)

        for month, year, units, _demand, _amount in rows:
            if month == current_month and year == current_year:
                if units is not None and 0 < units <= 1000000:
                    return units

    if detect_bill_format(text) == "legacy_msedcl":
        lines = _lines(text)

        for i, line in enumerate(lines[:60]):
            if (
                re.search(r"CURRENT\s+READ", line, re.I)
                or re.search(r"PREVIOUS\s+READ", line, re.I)
            ):
                for candidate in lines[i + 1:i + 6]:
                    nums = re.findall(
                        r"(?<![\d/])\d+(?:\.\d+)?(?![\d/])", candidate
                    )
                    if len(nums) >= 6:
                        value = clean_number(nums[3])
                        if value is not None and 0 < value <= 1000000:
                            return value

        for i, line in enumerate(lines[:60]):
            if re.fullmatch(r"NORMAL", line, re.I):
                for candidate in lines[max(0, i - 6):i]:
                    nums = re.findall(
                        r"(?<![\d/])\d+(?:\.\d+)?(?![\d/])", candidate
                    )
                    if len(nums) >= 6:
                        value = clean_number(nums[3])
                        if value is not None and 0 < value <= 1000000:
                            return value

    if detect_bill_format(text) == "legacy_msedcl":
        lines = _lines(text)

        # Old Marathi MSEDCL bills can lose the meter-table headers.
        # The stable OCR row is:
        # current reading, previous reading, MF, consumption, export, total
        # Example: 20398 20294 01 104 0 104
        for i, line in enumerate(lines[:70]):
            if re.fullmatch(r"NORMAL", line, re.I):
                nearby = lines[max(0, i - 8):i]
                for candidate in nearby:
                    nums = re.findall(
                        r"(?<![\d/])\d+(?:\.\d+)?(?![\d/])",
                        candidate,
                    )
                    if len(nums) >= 6:
                        value = clean_number(nums[3])
                        if value is not None and 0 < value <= 1000000:
                            return value

        # Header-preserved version.
        for i, line in enumerate(lines[:70]):
            if (
                re.search(r"CURRENT\s+READ", line, re.I)
                or re.search(r"PREVIOUS\s+READ", line, re.I)
            ):
                for candidate in lines[i + 1:i + 8]:
                    nums = re.findall(
                        r"(?<![\d/])\d+(?:\.\d+)?(?![\d/])",
                        candidate,
                    )
                    if len(nums) >= 6:
                        value = clean_number(nums[3])
                        if value is not None and 0 < value <= 1000000:
                            return value

    # Cross-format fallback for older MSEDCL meter tables where OCR splits
    # the header and row differently. Accept only a six-column numeric row
    # physically adjacent to the explicit NORMAL meter-status marker.
    lines = _lines(text)
    for i, line in enumerate(lines[:100]):
        if not re.fullmatch(r"NORMAL", line, re.I):
            continue
        for candidate in lines[max(0, i - 10):min(len(lines), i + 3)]:
            nums = re.findall(
                r"(?<![\d/])\d+(?:,\d{3})*(?:\.\d+)?(?![\d/])",
                candidate,
            )
            if len(nums) >= 6:
                value = clean_number(nums[3])
                if value is not None and 0 < value <= 1000000:
                    return value

    return None


